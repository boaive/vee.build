/**
 * One CSV cell, RFC 4180 quoted. A value that a spreadsheet would read as a
 * formula (=, +, -, @, tab, return) is prefixed with an apostrophe, so an
 * enquiry cannot run anything in the owner's spreadsheet.
 */
export function csvCell(v: unknown): string {
  if (v === null || v === undefined) return '';
  let s = String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function toCsv(header: readonly string[], rows: readonly (readonly unknown[])[]): string {
  return [header.map(csvCell).join(','), ...rows.map((r) => r.map(csvCell).join(','))].join('\r\n') + '\r\n';
}
